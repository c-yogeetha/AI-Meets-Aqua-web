#!/usr/bin/env python3
"""
scripts/make_hero_media.py - Generate hero media assets and bundled sample result.
Author: Matsya Project Team
"""

import json
import os
import shutil
import subprocess
import sys
from pathlib import Path
import imageio_ffmpeg

# Add backend directory to path
backend_dir = Path(__file__).resolve().parent.parent / "backend"
sys.path.insert(0, str(backend_dir))

from app.analysis.pipeline import run_pipeline


def main():
    ffmpeg_bin = imageio_ffmpeg.get_ffmpeg_exe()
    root = Path(__file__).resolve().parent.parent
    media_dir = root / "frontend" / "public" / "media"
    sample_dir = root / "frontend" / "public" / "sample"
    media_dir.mkdir(parents=True, exist_ok=True)
    sample_dir.mkdir(parents=True, exist_ok=True)

    # 1. Source selection
    real_source = root / "samples_real" / "hero_source.mp4"
    if real_source.exists():
        source_path = real_source
        is_synthetic = False
        source_desc = "samples_real/hero_source.mp4"
    else:
        source_path = root / "samples" / "stressed_one.mp4"
        if not source_path.exists():
            source_path = root / "samples" / "calm.mp4"
        is_synthetic = True
        source_desc = f"samples/{source_path.name}"

    print(f"Using source: {source_desc} (synthetic={is_synthetic})")

    # 2. Run analysis
    tmp_out = root / "storage" / "tmp_hero_analysis"
    tmp_out.mkdir(parents=True, exist_ok=True)

    meta = {
        "tank_id": "demo-tank-01",
        "tank_name": "Main Observation Tank",
        "tank_volume_liters": 120.0,
        "tank_fish_count": 3,
        "view": "side",
        "water_surface_y": 0.15,
        "pixel_to_cm": 0.1,
        "original_name": source_path.name,
    }

    result_dict = run_pipeline(
        video_path=str(source_path),
        meta=meta,
        out_dir=str(tmp_out),
        analyzer_override="baseline",
    )

    annotated_path = tmp_out / "annotated.mp4"

    # 3. Create MP4 loop (muted, 6-12s, 1280 or max width, under 4MB)
    hero_mp4 = media_dir / "hero.mp4"
    # Take first 10 seconds (150 frames)
    subprocess.run(
        [
            ffmpeg_bin,
            "-y",
            "-ss",
            "0",
            "-t",
            "10",
            "-i",
            str(annotated_path),
            "-an",
            "-vf",
            "scale=1280:-2",
            "-c:v",
            "libx264",
            "-pix_fmt",
            "yuv420p",
            "-profile:v",
            "main",
            "-movflags",
            "+faststart",
            "-crf",
            "23",
            str(hero_mp4),
        ],
        check=True,
    )

    # 4. Create WebM loop
    hero_webm = media_dir / "hero.webm"
    subprocess.run(
        [
            ffmpeg_bin,
            "-y",
            "-ss",
            "0",
            "-t",
            "10",
            "-i",
            str(annotated_path),
            "-an",
            "-vf",
            "scale=1280:-2",
            "-c:v",
            "libvpx-vp9",
            "-b:v",
            "0",
            "-crf",
            "32",
            str(hero_webm),
        ],
        check=True,
    )

    # 5. Extract poster frame at t=2.0s
    poster_jpg = media_dir / "hero-poster.jpg"
    subprocess.run(
        [
            ffmpeg_bin,
            "-y",
            "-ss",
            "00:00:02.000",
            "-i",
            str(hero_mp4),
            "-frames:v",
            "1",
            "-update",
            "1",
            "-q:v",
            "2",
            str(poster_jpg),
        ],
        check=True,
    )

    # 6. Copy media for sample section
    sample_mp4 = sample_dir / "annotated.mp4"
    shutil.copyfile(hero_mp4, sample_mp4)
    sample_poster = sample_dir / "poster.jpg"
    shutil.copyfile(poster_jpg, sample_poster)

    # Update result_dict media paths to point to public sample paths
    result_dict["annotated_video_url"] = "/sample/annotated.mp4"
    result_dict["annotated_video_alt_url"] = "/media/hero.webm"
    if "video" in result_dict and isinstance(result_dict["video"], dict):
        result_dict["video"]["poster_url"] = "/sample/poster.jpg"

    sample_json = sample_dir / "result.json"
    with open(sample_json, "w", encoding="utf-8") as f:
        json.dump(result_dict, f, indent=2, ensure_ascii=False)

    # 7. Write CREDITS.md
    credits_file = media_dir / "CREDITS.md"
    credits_content = f"""# Media Credits & Provenance

| Asset | Source | Licence | Author | Notes |
|---|---|---|---|---|
| `hero.mp4` | {source_desc} | Project Internal (CC0) | Matsya Project Team | {"Synthetic test clip generated by scripts/make_sample_videos.py" if is_synthetic else "Real footage from observation tank"} |
| `hero.webm` | {source_desc} | Project Internal (CC0) | Matsya Project Team | VP9 encoded variant |
| `hero-poster.jpg` | Extracted from `hero.mp4` at t=2.0s | Project Internal (CC0) | Matsya Project Team | Poster frame |
"""
    with open(credits_file, "w", encoding="utf-8") as f:
        f.write(credits_content)

    print("Hero media generated successfully:")
    print(f"  {hero_mp4} ({hero_mp4.stat().st_size / 1024:.1f} KB)")
    print(f"  {hero_webm} ({hero_webm.stat().st_size / 1024:.1f} KB)")
    print(f"  {poster_jpg} ({poster_jpg.stat().st_size / 1024:.1f} KB)")
    print(f"  {sample_json}")
    print(f"  {credits_file}")


if __name__ == "__main__":
    main()
